use super::*;

#[derive(Debug, Deserialize)]
#[serde(tag = "kind", content = "id", rename_all = "snake_case")]
pub enum DeleteTarget {
    Project(String),
    Conversation(String),
}

impl DeleteTarget {
    fn id(&self) -> &str {
        match self {
            Self::Project(id) | Self::Conversation(id) => id,
        }
    }
}

fn deletion_error() -> LibraryError {
    LibraryError::new("delete_history", "Não foi possível concluir a exclusão dos históricos. Verifique as permissões e tente excluir novamente.")
}

fn recovery_error() -> LibraryError {
    LibraryError::new("delete_recovery", "Não foi possível restaurar um histórico após uma exclusão incompleta. Os arquivos foram preservados; verifique as permissões e tente novamente.")
}

fn is_directory(path: &Path) -> Result<bool, LibraryError> {
    match fs::symlink_metadata(path) {
        Ok(meta) if meta.is_dir() && !meta.is_symlink() => Ok(true),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        _ => Err(deletion_error()),
    }
}

fn history_root(home: &Path) -> Result<Option<PathBuf>, LibraryError> {
    let root = home.join(".jarvis");
    if !is_directory(&root)? {
        return Ok(None);
    }
    let root = root.join("sessions");
    Ok(is_directory(&root)?.then_some(root))
}

// Recognize only Jarvis journals and the recovery copies generated by its journal reader.
fn history_id(filename: &str) -> Option<&str> {
    let stem = filename.strip_suffix(".jsonl")?;
    if valid_id(stem) {
        return Some(stem);
    }
    let (id, recovery) = stem.split_once(".recovery-")?;
    (valid_id(id) && valid_id(recovery)).then_some(id)
}

fn regular_file(path: &Path) -> Result<(), LibraryError> {
    let metadata = fs::symlink_metadata(path).map_err(|_| deletion_error())?;
    if !metadata.is_file() || metadata.is_symlink() {
        return Err(deletion_error());
    }
    Ok(())
}

fn sync_directory(directory: &Path) -> Result<(), LibraryError> {
    #[cfg(unix)]
    File::open(directory)
        .and_then(|file| file.sync_all())
        .map_err(|_| deletion_error())?;
    #[cfg(not(unix))]
    let _ = directory;
    Ok(())
}

fn restore(staged: &[(PathBuf, PathBuf)]) -> Result<(), LibraryError> {
    for (original, pending) in staged.iter().rev() {
        regular_file(pending).map_err(|_| recovery_error())?;
        match fs::symlink_metadata(original) {
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            _ => return Err(recovery_error()),
        }
        fs::rename(pending, original).map_err(|_| recovery_error())?;
        sync_directory(original.parent().ok_or_else(recovery_error)?)
            .map_err(|_| recovery_error())?;
    }
    Ok(())
}

/// SQLite decides whether an interrupted staged deletion must be restored or completed.
pub(super) fn recover(connection: &Connection, home: &Path) -> Result<(), LibraryError> {
    let Some(root) = history_root(home)? else {
        return Ok(());
    };
    for project_entry in fs::read_dir(root).map_err(|_| deletion_error())? {
        let entry = project_entry.map_err(|_| deletion_error())?;
        let project_id = entry.file_name().to_string_lossy().into_owned();
        if !valid_id(&project_id) {
            continue;
        }
        let kind = entry.file_type().map_err(|_| deletion_error())?;
        if !kind.is_dir() || kind.is_symlink() {
            continue;
        }
        let directory = entry.path();
        for entry in fs::read_dir(&directory).map_err(|_| deletion_error())? {
            let entry = entry.map_err(|_| deletion_error())?;
            let filename = entry.file_name().to_string_lossy().into_owned();
            let Some((original_name, whole_project)) = filename
                .strip_suffix(".project-deleting")
                .map(|name| (name, true))
                .or_else(|| filename.strip_suffix(".deleting").map(|name| (name, false)))
            else {
                continue;
            };
            let Some(id) = history_id(original_name) else {
                continue;
            };
            regular_file(&entry.path())?;
            let exists = if whole_project {
                connection.query_row(
                    "SELECT EXISTS(SELECT 1 FROM projects WHERE id = ?1)",
                    [&project_id],
                    |row| row.get::<_, bool>(0),
                )?
            } else {
                connection.query_row(
                    "SELECT EXISTS(SELECT 1 FROM conversations WHERE id = ?1 AND project_id = ?2)",
                    params![id, project_id],
                    |row| row.get::<_, bool>(0),
                )?
            };
            if exists {
                restore(&[(directory.join(original_name), entry.path())])?;
            } else {
                fs::remove_file(entry.path()).map_err(|_| deletion_error())?;
                sync_directory(&directory)?;
            }
        }
    }
    Ok(())
}

pub(crate) fn conversation_ids(
    connection: &Connection,
    target: &DeleteTarget,
) -> Result<Vec<String>, LibraryError> {
    if !valid_id(target.id()) {
        return Err(LibraryError::missing());
    }
    let sql = match target {
        DeleteTarget::Project(_) => "SELECT id FROM conversations WHERE project_id = ?1",
        DeleteTarget::Conversation(_) => "SELECT id FROM conversations WHERE id = ?1",
    };
    Ok(connection
        .prepare(sql)?
        .query_map([target.id()], |row| row.get(0))?
        .collect::<Result<_, _>>()?)
}

fn files_to_delete(
    home: &Path,
    project_id: &str,
    conversation_id: Option<&str>,
) -> Result<Vec<PathBuf>, LibraryError> {
    if !valid_id(project_id) {
        return Err(deletion_error());
    }
    let Some(root) = history_root(home)? else {
        return Ok(vec![]);
    };
    let directory = root.join(project_id);
    if !is_directory(&directory)? {
        return Ok(vec![]);
    }
    let mut files = vec![];
    for entry in fs::read_dir(directory).map_err(|_| deletion_error())? {
        let entry = entry.map_err(|_| deletion_error())?;
        let filename = entry.file_name().to_string_lossy().into_owned();
        let Some(id) = history_id(&filename) else {
            continue;
        };
        if conversation_id.is_some_and(|selected| selected != id) {
            continue;
        }
        regular_file(&entry.path())?;
        files.push(entry.path());
    }
    Ok(files)
}

pub(crate) fn delete(
    connection: &mut Connection,
    home: &Path,
    target: &DeleteTarget,
) -> Result<LibrarySnapshot, LibraryError> {
    if !valid_id(target.id()) {
        return Err(LibraryError::missing());
    }
    recover(connection, home)?;
    let project_id: Option<String> = match target {
        DeleteTarget::Project(id) => connection
            .query_row("SELECT id FROM projects WHERE id = ?1", [id], |row| {
                row.get(0)
            })
            .optional()?,
        DeleteTarget::Conversation(id) => connection
            .query_row(
                "SELECT project_id FROM conversations WHERE id = ?1",
                [id],
                |row| row.get(0),
            )
            .optional()?,
    };
    // A retry after a committed deletion only needs to finish cleanup above.
    let Some(project_id) = project_id else {
        return snapshot(connection);
    };
    let selected_conversation = match target {
        DeleteTarget::Conversation(id) => Some(id.as_str()),
        _ => None,
    };
    let files = files_to_delete(home, &project_id, selected_conversation)?;
    let mut staged = vec![];
    let result = (|| {
        let tx = connection.transaction_with_behavior(TransactionBehavior::Immediate)?;
        for original in files {
            let suffix = if matches!(target, DeleteTarget::Project(_)) {
                "project-deleting"
            } else {
                "deleting"
            };
            let pending = original.with_file_name(format!(
                "{}.{suffix}",
                original
                    .file_name()
                    .ok_or_else(deletion_error)?
                    .to_string_lossy()
            ));
            match fs::symlink_metadata(&pending) {
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                _ => return Err(deletion_error()),
            }
            fs::rename(&original, &pending).map_err(|_| deletion_error())?;
            staged.push((original, pending));
        }
        if let Some((original, _)) = staged.first() {
            sync_directory(original.parent().ok_or_else(deletion_error)?)?;
        }
        match target {
            DeleteTarget::Conversation(id) => {
                tx.execute("UPDATE navigation_selection SET conversation_id = NULL WHERE conversation_id = ?1", [id])?;
                tx.execute("DELETE FROM conversations WHERE id = ?1", [id])?;
            }
            DeleteTarget::Project(id) => {
                tx.execute("UPDATE navigation_selection SET project_id = NULL, conversation_id = NULL WHERE project_id = ?1", [id])?;
                tx.execute("DELETE FROM conversations WHERE project_id = ?1", [id])?;
                tx.execute("DELETE FROM projects WHERE id = ?1", [id])?;
            }
        }
        let result = snapshot(&tx)?;
        tx.commit()?;
        Ok(result)
    })();
    let result = match result {
        Ok(result) => result,
        Err(error) => {
            restore(&staged)?;
            return Err(error);
        }
    };
    for (_, pending) in &staged {
        fs::remove_file(pending).map_err(|_| deletion_error())?;
    }
    if let Some((original, _)) = staged.first() {
        sync_directory(original.parent().ok_or_else(deletion_error)?)?;
    }
    if matches!(target, DeleteTarget::Project(_)) {
        // Remove an empty history directory only; unknown files and project source are never traversed.
        let _ = fs::remove_dir(home.join(".jarvis").join("sessions").join(project_id));
    }
    Ok(result)
}
